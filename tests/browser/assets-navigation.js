async (page, { base = new URL(page.url()).origin } = {}) => {
  const errors = [], nativeDialogs = [], deletes = [];
  const image = await page.evaluate(() => {
    const canvas = document.createElement('canvas');
    canvas.width = 1000; canvas.height = 600;
    const context = canvas.getContext('2d');
    context.fillStyle = '#ffffff'; context.fillRect(0, 0, 1000, 600);
    context.fillStyle = '#222222'; context.font = '32px sans-serif';
    context.fillText('题目截图 · 预览验证', 64, 100);
    context.font = '24px sans-serif';
    context.fillText('给定数组 [2, 4, 6, 8]，计算所有元素之和。', 64, 180);
    context.fillText('可放大查看，也可使用左右按钮切换图片。', 64, 240);
    context.fillStyle = '#f2f3f5'; context.fillRect(64, 300, 872, 180);
    context.fillStyle = '#333333'; context.font = '26px monospace';
    context.fillText('2 + 4 + 6 + 8 = ?', 100, 400);
    return canvas.toDataURL('image/png');
  });
  const exams = Array.from({length:20}, (_, index) => ({id:`exam-${index}`,createdAt:'2026-10-31T10:00:00Z',query:`Question ${index}`,answer:`Answer ${index}\n`.repeat(40),images:[image,image],imageCount:2}));
  const sessions = [{id:'session-1',startedAt:'2026-10-31T10:00:00Z',turnCount:2,turns:[{role:'user',text:'Saved question',images:[image],imageCount:1},{role:'assistant',text:'Saved answer'}]}];
  const prefs = {study_specialty:'',study_language:'',answer_language:'zh-CN',assistant_role:'candidate',study_answer_style:'solution',study_goal:'',study_instructions:'',jd_text:'',resume_text:'',long_term_memory_consent:false};
  let heldResponse = null;
  let holdNext = false;
  let markHeld;
  const responseHeld = new Promise(resolve => { markHeld = resolve; });
  page.on('pageerror', error => errors.push(error.message));
  page.on('dialog', async dialog => { nativeDialogs.push(dialog.type()); await dialog.dismiss(); });
  await page.addInitScript(() => { window.__APP_SETTINGS__ = true; });
  await page.route('**/api/ui/settings', route => route.fulfill({json:prefs}));
  await page.route('**/api/config/llm/profiles', route => route.fulfill({json:{profiles:[],presets:[],active_profile_id:''}}));
  await page.route('**/api/learning-assets/**', async route => {
    const url = new URL(route.request().url());
    if(url.pathname.endsWith('/delete')) {
      deletes.push(route.request().postDataJSON().id);
      await route.fulfill({json:{ok:true}}); return;
    }
    if(url.pathname.endsWith('/exams') && holdNext) {
      holdNext = false;
      await new Promise(resolve => { heldResponse = resolve; markHeld(); });
    }
    await route.fulfill({json:{items:url.pathname.endsWith('/exams') ? exams : url.pathname.endsWith('/sessions') ? sessions : []}});
  });
  const check = (value, message) => { if(!value) throw Error(message); };
  await page.setViewportSize({width:1100,height:800});
  await page.goto(`${base}/settings#assets`);
  await page.locator('#examsList [data-view-exam]').last().waitFor();
  const target = page.locator('#examsList .asset-preview-link').nth(8);
  await target.scrollIntoViewIfNeeded();
  const scroll = await page.evaluate(() => window.scrollY);
  await target.click();
  await page.locator('#examsBack').waitFor();
  check(await page.evaluate(() => window.scrollY) < scroll, 'Opening a detail did not reset reading position');
  await page.locator('[data-preview-image]').first().click();
  await page.locator('dialog[open]').waitFor();
  await page.waitForFunction(() => {
    const image = document.querySelector('dialog .asset-image-stage img');
    return image?.complete && image.naturalWidth > 0;
  });
  await page.locator('[data-image-next]').click();
  check(await page.locator('[data-image-count]').textContent() === '2 / 2', 'Next image did not advance');
  await page.locator('[data-image-zoom]').click();
  check(await page.locator('dialog').evaluate(node => node.classList.contains('is-zoomed')), 'Zoom not enabled');
  await page.keyboard.press('Escape');
  check(await page.locator('dialog').count() === 0, 'Escape did not dismiss image');
  check(await page.locator('[data-preview-image]').first().evaluate(node => node === document.activeElement), 'Image close did not restore focus');
  await page.locator('#examsBack').click();
  await page.locator('#examsList [data-view-exam]').last().waitFor();
  await page.waitForFunction(y => Math.abs(window.scrollY-y) < 3, scroll);
  check(await page.locator('#examsList .asset-preview-link').nth(8).evaluate(node => node === document.activeElement), 'List lost keyboard focus');
  await page.goForward();
  await page.locator('#examsBack').waitFor();
  await page.evaluate(() => window.scrollTo(0, 600));
  await page.waitForFunction(() => history.state.assetScroll === window.scrollY && window.scrollY > 0);
  const detailScroll = await page.evaluate(() => window.scrollY);
  await page.goBack();
  await page.locator('#examsList [data-view-exam]').last().waitFor();
  await page.goForward();
  await page.locator('#examsBack').waitFor();
  await page.waitForFunction(y => Math.abs(window.scrollY-y) < 3, detailScroll);
  await page.reload();
  await page.locator('#examsBack').waitFor();
  await page.locator('[data-preview-image]').first().click();
  await page.evaluate(() => window.dispatchEvent(new Event('app:privacy-hidden')));
  check(await page.locator('dialog').count() === 0, 'Hide left an image preview open');
  await page.locator('[data-asset-tab="records"]').click();
  await page.locator('[data-view="session-1"]').click();
  await page.locator('#assetBack').waitFor();
  await page.locator('#assetRecords [data-preview-image]').click();
  await page.locator('[data-dialog-close]').click();
  await page.locator('#assetBack').click();
  await page.locator('[data-delete="session-1"]').click();
  await page.locator('dialog [data-confirm]').waitFor();
  await page.evaluate(() => window.dispatchEvent(new Event('app:privacy-hidden')));
  check(deletes.length === 0, 'Privacy hide confirmed a deletion');
  await page.locator('[data-delete="session-1"]').click();
  await page.locator('[data-confirm]').click();
  await page.waitForFunction(() => !document.querySelector('dialog'));
  check(deletes.length === 1, 'Confirmed deletion did not run exactly once');
  await page.goto(`${base}/settings#assets/exams/missing`);
  await page.getByText('这条笔试记录已不存在。').waitFor();
  await page.locator('[data-asset-back]').click();
  await page.locator('#examsList [data-view-exam]').last().waitFor();
  holdNext = true;
  await page.locator('[data-view-exam]').first().click();
  await responseHeld;
  await page.locator('[data-asset-tab="records"]').click();
  await page.locator('[data-view="session-1"]').waitFor();
  check(heldResponse, 'Slow response was not exercised');
  heldResponse();
  await page.locator('[data-view="session-1"]').click();
  await page.locator('#assetBack').waitFor();
  check(await page.locator('#assetRecords').isVisible(), 'Stale exam response changed current tab');
  await page.setViewportSize({width:375,height:812});
  await page.locator('#assetRecords [data-preview-image]').click();
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile document overflows');
  const bounds = await page.locator('dialog').boundingBox();
  check(bounds.x >= 0 && bounds.x + bounds.width <= 376, 'Mobile dialog overflows');
  await page.keyboard.press('Escape');
  check(nativeDialogs.length === 0, 'An OS dialog escaped the protected window');
  check(errors.length === 0, errors.join('\n'));
  return {passed:true,detailHistory:true,restoreListScroll:true,reloadDetail:true,imagesClickable:true,imageNavigationAndZoom:true,privacyDismissal:true,confirmationInsideWindow:true,staleResponseIgnored:true,mobile:true};
}
