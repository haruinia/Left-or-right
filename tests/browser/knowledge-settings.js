async (page, {base=new URL(page.url()).origin}={})=>{
  const errors=[],patches=[];
  page.on('pageerror',error=>errors.push(error.message));
  const initial=await(await page.request.get(`${base}/api/ui/settings`,{headers:{'user-agent':'Left-or-right UI test'}})).json();
  let settings={...initial,interview_use_knowledge:false,interview_knowledge_project_ids:[],study_language:'Java',jd_text:'保留的岗位',resume_text:'保留的简历'};
  const projects=[{id:'project-a',name:'测试项目资料',document_count:2},{id:'project-b',name:'未选项目资料',document_count:1}];
  await page.route('**/api/ui/settings',async route=>{
    if(route.request().method()==='PATCH'){const body=route.request().postDataJSON();patches.push(body);settings={...settings,...body};}
    await route.fulfill({json:settings});
  });
  await page.route('**/api/config/llm/profiles',route=>route.fulfill({json:{profiles:[],presets:[],active_profile_id:''}}));
  await page.route('**/api/learning-assets/**',route=>route.fulfill({json:{items:[]}}));
  await page.route('**/api/knowledge/projects',route=>route.fulfill({json:{projects}}));
  const check=(value,message)=>{if(!value)throw Error(message);};
  await page.setViewportSize({width:1100,height:850});
  await page.goto(`${base}/settings?knowledge-test#briefing`);
  const checkbox=page.locator('#interviewUseKnowledge');
  await page.waitForFunction(()=>!document.querySelector('#interviewUseKnowledge').disabled);
  check(!await checkbox.isVisible(),'Materials summary exposes the knowledge editor');
  await page.locator('#editBriefingKnowledge').click();
  await page.locator('[data-knowledge-select="project-a"]').waitFor();
  check(!await checkbox.isChecked(),'Historical notes must not start enabled');
  check((await page.locator('#interviewKnowledgeHint').textContent()).includes('发送给当前模型'),'Outbound reference disclosure missing');
  check(await checkbox.count()===1,'Historical note controls duplicated');
  check(!await page.locator('[data-knowledge-select="project-a"]').isChecked()&&!await page.locator('[data-knowledge-select="project-b"]').isChecked(),'New projects were implicitly selected');
  await checkbox.check();await page.locator('#saveUiSettings').click();
  await page.waitForFunction(()=>document.querySelector('#saveUiSettings').disabled);
  check(JSON.stringify(patches.at(-1))===JSON.stringify({interview_use_knowledge:true}),'Saving note consent overwrote another setting');
  await page.locator('[data-knowledge-select="project-a"]').check();await page.locator('#saveUiSettings').click();
  await page.waitForFunction(()=>document.querySelector('#saveUiSettings').disabled);
  check(JSON.stringify(patches.at(-1))===JSON.stringify({interview_knowledge_project_ids:['project-a']}),'Project selection did not save only selected project IDs');
  await page.reload();
  await page.waitForFunction(()=>!document.querySelector('#interviewUseKnowledge').disabled);
  await page.locator('[data-knowledge-select="project-a"]').waitFor();
  check(await checkbox.isChecked()&&await page.locator('[data-knowledge-select="project-a"]').isChecked(),'Explicit material selection did not survive reopening');
  check(!await page.locator('[data-knowledge-select="project-b"]').isChecked(),'Unselected project was included after reopening');
  check(await page.locator('#jdText').inputValue()==='保留的岗位'&&await page.locator('#resumeText').inputValue()==='保留的简历','Briefing fields changed');
  await page.locator('[data-briefing-detail="knowledge"] a[href="#knowledge"]').click();
  await page.waitForFunction(()=>!document.querySelector('#knowledge').hidden);
  check(await page.locator('.settings-nav a[href="#knowledge"]').getAttribute('aria-current')==='page','Manage knowledge link did not select its own section');
  await page.goBack();await page.waitForFunction(()=>!document.querySelector('[data-briefing-detail="knowledge"]').hidden);
  await checkbox.uncheck();await page.locator('#saveUiSettings').click();
  await page.waitForFunction(()=>document.querySelector('#saveUiSettings').disabled);
  check(JSON.stringify(patches.at(-1))===JSON.stringify({interview_use_knowledge:false}),'Disabling historical notes overwrote the project selection');
  check(settings.interview_knowledge_project_ids.length===1,'Historical-note consent implicitly changed document selection');
  await page.locator('[data-knowledge-select="project-a"]').uncheck();await page.locator('#saveUiSettings').click();
  await page.waitForFunction(()=>document.querySelector('#saveUiSettings').disabled);
  check(JSON.stringify(patches.at(-1))===JSON.stringify({interview_knowledge_project_ids:[]}),'Clearing project selection did not retain unrelated preferences');
  await page.setViewportSize({width:375,height:812});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Knowledge setting overflows narrow layout');
  check(errors.length===0,errors.join('\n'));
  return {passed:true,optInDefaultOff:true,explicitProjectSelection:true,historicalNotesIndependent:true,outboundDisclosure:true,patchIsolation:true,reloadPersistence:true,knowledgeDeepLink:true,narrowLayout:true};
}
